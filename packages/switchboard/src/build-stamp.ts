/**
 * @module @dsh-brain/switchboard/build-stamp
 *
 * 控制面 / gen 插件的**代码身份戳**。
 *
 * ★ 为什么要一个常量（格⑮ 踩到的真实坑的预防）
 *
 * 本仓库的插件是经 **profile 的 `node_modules` 软链**（`link:`）解析的，而 `lib/` 又被
 * `scripts/build.mjs` 翻成一个指向 `out/<buildId>` 的 junction。于是"我改了源码"与"跑起来的
 * 是改后的源码"之间隔着**三道**可能出错的东西：junction 指向哪个 buildId、profile 的软链指向
 * 哪个包目录、进程是什么时候起的。
 *
 * 预演体检的结论如果建立在"我以为是新代码"上，那它连自己都证不了。所以：
 *   ① 控制面把 `BUILD_STAMP` 放进 `?cmd=preflight` 的报告（`report.build`）；
 *   ② gen 侧把它放进 `/admin/inventory` 的返回（`inv.build`）；
 *   ③ 报告里两者**对账**（不一致 ⇒ 本次预演的"活实例读数"来自另一份代码，必须当场看出来）。
 *
 * 改这个值 = 改一次代码身份（就像一次 build id）。它**不参与业务逻辑**。
 *
 * ★ 取值口径（主仓 `dsh-brain` 自己的戳）
 *
 * 形状是 `<身份前缀>-<能力名>-<日期>.<修订>`。前缀写**这份代码属于谁**：
 *   · 本包在主仓里跑 ⇒ 前缀 = 主仓身份 `dsh-brain`（依据：根 `package.json#name=dsh-brain`、
 *     远端 `github.com/xr192172/dsh-brain`、插件 scope `@dsh-brain/*` —— 三者一致）；
 *   · 若某次实验在**一棵独立的臂树**里重放这份代码，则该臂必须把前缀改成**它自己的**身份
 *     （例如 `b2-…` / `replay-b2-…`），好让"这份读数出自哪棵树"在证据里可当场分辨。
 *   ⇒ 换句话说：**前缀是"树身份"，不是"能力名"**。主仓代码里不该出现任何"臂"字样。
 *
 * ★ 对账对的是谁、会不会误报
 *
 * 对账的两端是**同一次预演**里的两个进程，且**都从本文件的同一份源码编译出来**：
 *   控制面进程（`main.js`，把值写进 `report.build`）  ⟷  预演代进程（`index.js`，把值写进 `inv.build`）。
 * 二者一致 ⇒ 本次"活实例读数"确实来自控制面正在驱动的这份代码。
 *
 * 它**不**与现役（活跃代）比对：`preflight` 从不读现役代，只读它自己刚 spawn 的预演代
 * （见 `preflight.ts` 的 INVARIANT）。所以**现状不存在"和现役比 ⇒ 误报"的路径**。
 * 若将来有人扩展成"也读现役代"：现役代是上一次构建的代码 ⇒ 戳不同是**真信号**（现役代跑的是
 * 旧代码，需要换代），不是误报。
 */
